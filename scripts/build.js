#!/usr/bin/env node
/*
 * Build: no dependencies. Produces committed outputs so nobody needs Node to deploy.
 *   apps-script/dist/Code.gs        one file to paste into Extensions → Apps Script
 *   apps-script/dist/appsscript.json
 *   site/js/canopy-core.js          the same engine code, for the browser
 *   site/r/<slot>/index.html        stable room routes (/r/1 … /r/10)
 *   site/join/index.html            stable main-call route (/join)
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const core = require(path.join(root, 'core'));
const coreSrc = core.FILES.map((f) => `// ---- core/${path.basename(f)} ----\n` + fs.readFileSync(f, 'utf8')).join('\n');
const gasSrc = ['SheetStore.js', 'Main.js'].map((f) => `// ---- apps-script/src/${f} ----\n` + fs.readFileSync(path.join(root, 'apps-script/src', f), 'utf8')).join('\n');
const banner = `/*\n * Canopy engine v${core.VERSION} — GENERATED by scripts/build.js. Do not edit here;\n * edit core/ and apps-script/src/ and rebuild. Paste this whole file into Code.gs.\n */\n`;
fs.mkdirSync(path.join(root, 'apps-script/dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'apps-script/dist/Code.gs'), banner + coreSrc + '\n' + gasSrc);
fs.writeFileSync(
  path.join(root, 'apps-script/dist/appsscript.json'),
  JSON.stringify(
    {
      timeZone: 'America/Chicago',
      runtimeVersion: 'V8',
      exceptionLogging: 'STACKDRIVER',
      webapp: { executeAs: 'USER_DEPLOYING', access: 'ANYONE_ANONYMOUS' }
    },
    null,
    2
  ) + '\n'
);
fs.mkdirSync(path.join(root, 'site/js'), { recursive: true });
fs.writeFileSync(path.join(root, 'site/js/canopy-core.js'), `/* GENERATED from core/ by scripts/build.js */\n` + coreSrc);

function redirectPage(title, hashRoute, depth) {
  const up = '../'.repeat(depth);
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title} — Canopy</title><meta name="robots" content="noindex">
<link rel="stylesheet" href="${up}css/site.css"></head>
<body><main class="wrap redirect"><h1>${title}</h1><p id="msg">Finding the current link…</p>
<p><a href="${up}index.html#/${hashRoute}">Go to the Canopy page for this room</a></p></main>
<script src="${up}js/config.js"></script><script src="${up}js/canopy-core.js"></script><script src="${up}js/data.js"></script>
<script>CanopyData.resolveStableRoute(${JSON.stringify(hashRoute)}, "${up}");</script></body></html>
`;
}
for (let slot = 1; slot <= 10; slot++) {
  const dir = path.join(root, 'site/r', String(slot));
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), redirectPage('Working-group room ' + slot, 'rooms/' + slot, 2));
}
fs.mkdirSync(path.join(root, 'site/join'), { recursive: true });
fs.writeFileSync(path.join(root, 'site/join/index.html'), redirectPage('Join the monthly Canopy call', 'join', 1));
console.log('Built Code.gs (' + Math.round(fs.statSync(path.join(root, 'apps-script/dist/Code.gs')).size / 1024) + ' KB), site core, 11 stable routes.');
